#!/usr/bin/env python3
"""Static coverage check for the application font subset.

Reads assets/fonts/app_font_16.c (generated by tools/gen_app_font.sh) and proves
that every required code point -- printable ASCII plus assets/fonts/app_font_16.chars --
is reachable through the font's cmap tables using LVGL 9.5 lookup semantics.

This is a host-side gate: it does not render on the device, but it catches the
"UTF-8 string with no glyph" class of defects that a successful build cannot.
"""
import pathlib
import re
import sys

ROOT = pathlib.Path(__file__).resolve().parents[1]
FONT_C = ROOT / "assets" / "fonts" / "app_font_16.c"
CHARS = ROOT / "assets" / "fonts" / "app_font_16.chars"


def fail(message):
    print(f"app font coverage: FAIL - {message}", file=sys.stderr)
    sys.exit(1)


def main():
    if not FONT_C.is_file():
        fail(f"{FONT_C} is missing; run tools/gen_app_font.sh")
    if not CHARS.is_file():
        fail(f"{CHARS} is missing")

    text = FONT_C.read_text(encoding="utf-8")

    # Structural contract of the generated font.
    for needle, label in [
        ("const lv_font_t app_font_16", "public symbol app_font_16"),
        ("#include \"lvgl.h\"", "lvgl.h include"),
        (".bpp = 4", "4 bpp"),
        (".bitmap_format = 0", "plain bitmap format"),
        (".kern_dsc = NULL", "no kerning tables"),
        (".line_height = 20", "line height 20"),
        (".base_line = 5", "base line 5"),
    ]:
        if needle not in text:
            fail(f"generated font is missing {label} ({needle!r})")

    # unicode_list_N arrays (SPARSE cmaps only).
    unicode_lists = {}
    for name, body in re.findall(
        r"static const uint16_t (unicode_list_\d+)\[\]\s*=\s*\{(.*?)\n\};", text, re.S
    ):
        unicode_lists[name] = [int(v, 16) for v in re.findall(r"0x([0-9a-fA-F]+)", body)]

    covered = set()
    cmap_count = 0
    for match in re.finditer(
        r"\.range_start\s*=\s*(\d+),\s*\.range_length\s*=\s*(\d+),\s*"
        r"\.glyph_id_start\s*=\s*(\d+),\s*"
        r"\.unicode_list\s*=\s*(\w+),\s*\.glyph_id_ofs_list\s*=\s*(\w+),\s*"
        r"\.list_length\s*=\s*(\d+),\s*"
        r"\.type\s*=\s*LV_FONT_FMT_TXT_CMAP_(\w+)",
        text,
    ):
        start = int(match.group(1))
        length = int(match.group(2))
        unicode_list = match.group(4)
        list_length = int(match.group(6))
        cmap_type = match.group(7)
        cmap_count += 1
        if match.group(5) != "NULL":
            fail("glyph_id_ofs_list is not supported by this check")
        if cmap_type == "FORMAT0_TINY":
            covered.update(range(start, start + length))
        elif cmap_type == "SPARSE_TINY":
            offsets = unicode_lists.get(unicode_list)
            if offsets is None:
                fail(f"cmap references unknown {unicode_list}")
            if len(offsets) != list_length:
                fail(f"{unicode_list} length {len(offsets)} != listed {list_length}")
            for offset in offsets:
                if offset > 0xFFFF:
                    fail(f"offset {offset} does not fit a 16-bit unicode_list entry")
                covered.add(start + offset)
        else:
            fail(f"unexpected cmap type {cmap_type}")

    if cmap_count == 0:
        fail("no cmap entries parsed")

    required = set(range(0x20, 0x7F))
    for index, line in enumerate(CHARS.read_text(encoding="utf-8").splitlines(), 1):
        line = line.strip()
        if not line:
            continue
        if len(line) != 1:
            fail(f"{CHARS.name}:{index} must contain exactly one character")
        required.add(ord(line))

    missing = sorted(required - covered)
    if missing:
        detail = ", ".join(f"U+{cp:04X} {chr(cp)!r}" for cp in missing)
        fail(f"required code points missing from the font subset: {detail}")

    # Second gate: every Chinese literal the UI can render must be in the
    # inventory. LCD text lives in main/ble_scan_ui.c; other main/*.c Chinese
    # strings are serial log messages and are not drawn on the display.
    # Without this gate, a new Chinese label outside app_font_16.chars would
    # pass the font check but render as placeholder boxes on the device.
    cjk_re = re.compile(r"[\u3400-\u4dbf\u4e00-\u9fff]")
    ui_source = (ROOT / "main" / "ble_scan_ui.c").read_text(encoding="utf-8")
    ui_source = re.sub(r"/\*.*?\*/", "", ui_source, flags=re.S)
    ui_source = re.sub(r"//[^\n]*", "", ui_source)
    outside = sorted({ch for ch in ui_source
                      if cjk_re.match(ch) and ord(ch) not in required})
    if outside:
        detail = ", ".join(f"U+{ord(ch):04X} {ch!r}" for ch in outside)
        fail(f"Chinese UI literals outside the font inventory: {detail}")

    print(
        f"app font coverage: PASS ({len(required)} required code points, "
        f"{len(covered)} covered, {cmap_count} cmaps, UI literals covered)"
    )


if __name__ == "__main__":
    main()
